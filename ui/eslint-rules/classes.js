import resolveConfig from "tailwindcss/resolveConfig.js";
import contextUtils from "tailwindcss/lib/lib/setupContextUtils.js";
import tailwindConfig from "../tailwind.config.js";

const resolved = resolveConfig(tailwindConfig);

// A scale still inheriting Tailwind's defaults is invisible to this rule by
// construction: every one of its members emits, so no class drawn from it can
// ever red. `fontWeight` sat open through step ① and all nine magnitudes were
// legal with nothing able to say so (E-DFLOW.W6 step 2). Legality is therefore
// membership of a scale the project DECLARES, not merely one Tailwind can emit
// — so the config must name every scale the code draws from.
const stock = resolveConfig({ content: [] }).theme;
const declared = new Set(Object.keys(tailwindConfig.theme));
const inheritedScales = Object.keys(stock).filter(
  (key) =>
    !declared.has(key) && JSON.stringify(resolved.theme[key]) === JSON.stringify(stock[key]),
);

// Every consumer builds its context through here, so no second reader can be
// born unguarded: the vocabulary emitter empties one more scale to learn which
// classes that scale owns, and must see the same closed config this rule does.
export function closedContext(emptied = {}) {
  return contextUtils.createContext(
    resolveConfig({
      ...tailwindConfig,
      theme: {
        ...tailwindConfig.theme,
        ...Object.fromEntries(inheritedScales.map((key) => [key, {}])),
        ...emptied,
      },
    }),
  );
}

const context = closedContext();

// The closed config is the vocabulary and this list is its members: every class
// the config can emit, generated by Tailwind itself rather than transcribed.
// A class is legal iff it is here — which classifies on the whole (prefix,
// value) pair, so `text-center` and `text-body` are judged apart from `text-lg`
// without a hand-written prefix table.
export const emittableClasses = context.getClassList();

const EMITTABLE = new Set(emittableClasses);

// A `/step` draws from the scale its own base draws from, never from one global
// step list: `text-` is a colour prefix and a size prefix at once, so
// `text-ink/wash` dims a colour while `text-body/loose` sets a line height, and
// Tailwind emits nothing at all — not even the base — for the wrong pairing.
export const modifierSteps = new Map();
for (const entry of context.getClassList({ includeMetadata: true })) {
  if (!Array.isArray(entry)) continue;
  const [names, meta] = entry;
  for (const name of [names].flat()) modifierSteps.set(name, new Set(meta?.modifiers ?? []));
}

const STATIC_UTILITIES = new Set(
  [...context.candidateRuleMap.keys()].filter((k) => typeof k === "string"),
);

const ARBITRARY = /\[([^\]]*)\]/;

export function stripVariants(cls) {
  let depth = 0;
  let base = 0;
  for (let i = 0; i < cls.length; i += 1) {
    const c = cls[i];
    if (c === "[") depth += 1;
    else if (c === "]") depth -= 1;
    else if (c === ":" && depth === 0) base = i + 1;
  }
  return cls.slice(base).replace(/^!/, "");
}

export function arbitraryValue(cls) {
  const match = ARBITRARY.exec(stripVariants(cls));
  return match ? match[1] : null;
}

// The unit is trimmed, never recognised: a whitelist dates the moment CSS grows
// a unit, and `h-[100dvh]` was excused here while the design surface — which
// trims — rejected it. One rule, one dialect (DEC-17).
export function isBareSize(value) {
  const magnitude = value.replace(/[a-z%]+$/i, "");
  return /^[-.\d]+$/.test(magnitude) && /\d/.test(magnitude);
}

export function classify(cls) {
  const base = stripVariants(cls);
  if (base === "" || EMITTABLE.has(base)) return { legal: true };

  const arbitrary = ARBITRARY.exec(base);
  if (arbitrary) return { legal: false, kind: "arbitrary", value: arbitrary[1] };

  const slash = base.lastIndexOf("/");
  if (slash > 0) {
    const owner = base.slice(0, slash);
    const step = base.slice(slash + 1);
    const steps = modifierSteps.get(owner);
    if (steps?.size) {
      return steps.has(step)
        ? { legal: true }
        : { legal: false, kind: "modifier", value: step, owner, steps: [...steps] };
    }
  }
  return { legal: false, kind: "offlist" };
}

// Structural classes carry no value a scale could govern — Tailwind registers
// them whole rather than generating them from a theme key, so closing a scale
// can never reach them and the rule has nothing to judge.
export function isScaleBearing(cls) {
  return !STATIC_UTILITIES.has(stripVariants(cls));
}

function walk(node, visit, skip) {
  if (!node || typeof node.type !== "string") return;
  if (skip?.(node)) return;
  visit(node);
  const ignored = skip ? (NON_VALUE_KEYS[node.type] ?? []) : [];
  for (const key of Object.keys(node)) {
    if (key === "parent" || ignored.includes(key)) continue;
    const child = node[key];
    if (Array.isArray(child)) child.forEach((c) => walk(c, visit, skip));
    else walk(child, visit, skip);
  }
}

// A string only becomes a class by being rendered, so the search follows value
// positions and stops at the ones that cannot produce one. Without this a
// followed declaration drags in every `state === "running"` and
// `setState("failed")` in its enclosing function.
const NON_VALUE_KEYS = {
  ConditionalExpression: ["test"],
  IfStatement: ["test"],
  SwitchStatement: ["discriminant"],
  SwitchCase: ["test"],
  WhileStatement: ["test"],
  DoWhileStatement: ["test"],
  ForStatement: ["test"],
  CallExpression: ["arguments"],
  NewExpression: ["arguments"],
  Property: ["key"],
  MemberExpression: ["property"],
};

const NON_VALUE_TYPES = new Set(["BinaryExpression", "ImportDeclaration", "JSXText"]);

const notAValue = (node) =>
  NON_VALUE_TYPES.has(node.type) ||
  node.type.startsWith("TS") ||
  (node.type === "JSXAttribute" && node.name?.name !== "className");

function referencedNames(node) {
  const names = new Set();
  walk(node, (n) => {
    if (n.type === "Identifier") names.add(n.name);
  }, notAValue);
  return names;
}

function tokensOf(text, textStart) {
  const found = [];
  const pattern = /\S+/g;
  let match = pattern.exec(text);
  while (match) {
    found.push({ cls: match[0], offset: textStart + match.index });
    match = pattern.exec(text);
  }
  return found;
}

// A class the rule cannot resolve is reported, never skipped: a quasi that runs
// into an interpolation holds half a class name, and half a class name is
// exactly how an off-list value hides from a static check.
function templateTokens(node) {
  const found = [];
  node.quasis.forEach((quasi, i) => {
    const text = quasi.value.cooked ?? quasi.value.raw;
    const start = quasi.range[0] + 1;
    const tokens = tokensOf(text, start);
    const openEnd = i < node.quasis.length - 1 && !/\s$/.test(text);
    const openStart = i > 0 && !/^\s/.test(text);
    tokens.forEach((token, j) => {
      const partial = (openStart && j === 0) || (openEnd && j === tokens.length - 1);
      found.push({ ...token, node: quasi, partial });
    });
  });
  return found;
}

// Requirement 2: the majority idiom in this codebase holds classes in constants
// and lookup maps, not at `className=`. Anchoring on the attribute alone misses
// them, so the attribute only seeds the search — every name it reaches is
// followed to its declaration, transitively.
export function collectClasses(program) {
  const declarations = new Map();
  const seeds = [];
  const wanted = new Set();

  // Every declaration of a name is kept, not just the last: following is by name
  // over the whole file, so two functions each holding `const cls = ...` would
  // otherwise leave one of them unread and the file reported clean.
  const declare = (name, node) => {
    const bound = declarations.get(name);
    if (bound) bound.push(node);
    else declarations.set(name, [node]);
  };

  walk(program, (node) => {
    if (node.type === "VariableDeclarator" && node.id.type === "Identifier" && node.init) {
      declare(node.id.name, node.init);
    }
    if (node.type === "FunctionDeclaration" && node.id) {
      declare(node.id.name, node.body);
    }
    if (node.type === "JSXAttribute" && node.name?.name === "className" && node.value) {
      seeds.push(node.value);
      referencedNames(node.value).forEach((n) => wanted.add(n));
    }
  });

  const roots = [...seeds];
  const followed = new Set();
  let pending = [...wanted];
  while (pending.length > 0) {
    const name = pending.pop();
    if (followed.has(name)) continue;
    followed.add(name);
    const bound = declarations.get(name);
    if (!bound) continue;
    roots.push(...bound);
    bound.forEach((init) =>
      pending.push(...[...referencedNames(init)].filter((n) => !followed.has(n))),
    );
  }

  const found = [];
  const visited = new Set();
  roots.forEach((root) =>
    walk(
      root,
      (node) => {
        if (visited.has(node)) return;
        visited.add(node);
        if (node.type === "Literal" && typeof node.value === "string") {
          tokensOf(node.value, node.range[0] + 1).forEach((token) =>
            found.push({ ...token, node, partial: false }),
          );
        } else if (node.type === "TemplateLiteral") {
          templateTokens(node).forEach((token) => found.push(token));
        }
      },
      notAValue,
    ),
  );
  return found;
}
